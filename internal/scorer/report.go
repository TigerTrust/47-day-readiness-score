package scorer

import (
	"encoding/json"
	"fmt"
	"io"
	"strings"
)

// WriteText writes a human-readable summary of r to w.
func (r *Report) WriteText(w io.Writer) {
	fmt.Fprintf(w, "Host:  %s:%d\n", r.Host, r.Port)
	fmt.Fprintf(w, "Score: %d / 100\n", r.Score)
	if r.NotAfter != "" {
		fmt.Fprintf(w, "Issuer: %s\n", r.Issuer)
		fmt.Fprintf(w, "NotAfter: %s  (%d days remaining, validity %d days)\n", r.NotAfter, r.DaysRemaining, r.ValidityDays)
	}
	fmt.Fprintln(w, "Checks:")
	for _, c := range r.Checks {
		mark := "FAIL"
		if c.Pass {
			mark = "PASS"
		}
		fmt.Fprintf(w, "  [%s] (-%d if fail) %-20s %s\n", mark, c.Weight, c.ID, c.Detail)
	}
	if len(r.Errors) > 0 {
		fmt.Fprintln(w, "Errors:")
		for _, e := range r.Errors {
			fmt.Fprintf(w, "  - %s\n", e)
		}
	}
}

// WriteJSON writes r as a JSON document.
func (r *Report) WriteJSON(w io.Writer) error {
	enc := json.NewEncoder(w)
	enc.SetIndent("", "  ")
	return enc.Encode(r)
}

// WriteMarkdown writes a GitHub-flavored markdown report for r.
func (r *Report) WriteMarkdown(w io.Writer) {
	fmt.Fprintf(w, "# 47-day readiness report: `%s:%d`\n\n", r.Host, r.Port)
	fmt.Fprintf(w, "**Score:** %d / 100\n\n", r.Score)
	if r.NotAfter != "" {
		fmt.Fprintf(w, "- Issuer: `%s`\n", r.Issuer)
		fmt.Fprintf(w, "- NotAfter: `%s`\n", r.NotAfter)
		fmt.Fprintf(w, "- Days remaining: `%d`\n", r.DaysRemaining)
		fmt.Fprintf(w, "- Validity window: `%d` days\n\n", r.ValidityDays)
	}
	fmt.Fprintln(w, "| Check | Pass | Weight | Detail |")
	fmt.Fprintln(w, "|-------|:----:|-------:|--------|")
	for _, c := range r.Checks {
		mark := ":x:"
		if c.Pass {
			mark = ":white_check_mark:"
		}
		fmt.Fprintf(w, "| `%s` | %s | %d | %s |\n", c.ID, mark, c.Weight, strings.ReplaceAll(c.Detail, "|", "\\|"))
	}
	if len(r.Errors) > 0 {
		fmt.Fprintln(w, "\n**Errors:**")
		for _, e := range r.Errors {
			fmt.Fprintf(w, "- %s\n", e)
		}
	}
	fmt.Fprintln(w, "\n_Report generated by [47-day-readiness-score](https://github.com/tigertrust/47-day-readiness-score) — Built by [TigerTrust](https://tigertrust.io)._")
}
